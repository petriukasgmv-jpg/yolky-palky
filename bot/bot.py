    user_histories[message.chat.id] = []

    bot.reply_to(
        message,
        "Привет! Я Ёлки-палки — твой ИИ-Бизнес-Стратег. 🚀\n\n"
        "Главная цель — помочь тебе выйти на €5 000 "
        "чистого дохода в месяц.\n\n"
        "Я буду анализировать идеи, считать деньги, "
        "искать актуальную информацию и помогать "
        "двигаться конкретными шагами.\n\n"
        "Давай работать."
    )


