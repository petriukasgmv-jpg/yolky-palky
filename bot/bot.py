app = Flask(__name__)


@app.route("/")
def home():

    return "Yolky Palky Business Strategist is running!"


@app.route("/health")
def health():

    return "OK"


def run_flask():

    port = int(
        os.environ.get(
            "PORT",
            10000
        )
    )

    app.run(
        host="0.0.0.0",
        port=port
    )


# =========================================================
# ЗАПУСК
# =========================================================

if __name__ == "__main__":

    try:

        bot.delete_webhook()

        print("Webhook удалён")

    except Exception as e:

        print(
            f"Не удалось удалить webhook: {e}"
        )


    threading.Thread(
        target=run_flask,
        daemon=True
    ).start()


    print(
        "Yolky Palky Business Strategist запущен!"
    )


    bot.infinity_polling(
        skip_pending=True
    )
