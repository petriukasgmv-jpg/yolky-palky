    # Устанавливаем webhook.
    # ВАЖНО: здесь больше НЕТ infinity_polling().
    try:

        result = bot.set_webhook(
            url=WEBHOOK_URL
        )

        print("Webhook set:", result)

    except Exception as e:

        print("Webhook setup error:", repr(e))

    port = int(os.getenv("PORT", "10000"))

    app.run(
        host="0.0.0.0",
        port=port
    )
